//! Production road-surface to terrain-CDT agreement tests on a baked imported DEM fixture.

use super::*;

const KUOPIO_IMPORTED_DEM_WIDTH: usize = 33;
const KUOPIO_IMPORTED_DEM_HEIGHT: usize = 33;
const KUOPIO_IMPORTED_DEM_CELL_M: f32 = 10.0;

#[test]
fn imported_dem_spans_preserve_real_terrain_cdt_agreement() {
    assert_production_dem_cases(vec![
        standard_span_dem_case(
            "grounded standard road on imported Kuopio lower shelf",
            kuopio_imported_dem_terrain(),
            Vector2::new(-120.0, 80.0),
            Vector2::new(-20.0, 80.0),
            0.0,
            12,
            (-138.0, 62.0, -2.0, 98.0),
            false,
            false,
        ),
        standard_span_dem_case(
            "grounded standard road crossing imported Kuopio steep terrain",
            kuopio_imported_dem_terrain(),
            Vector2::new(-100.0, 0.0),
            Vector2::new(100.0, 0.0),
            0.0,
            24,
            (-118.0, -28.0, 118.0, 28.0),
            false,
            true,
        ),
        standard_span_dem_case(
            "raised standard road over imported Kuopio steep terrain",
            kuopio_imported_dem_terrain(),
            Vector2::new(-90.0, 48.0),
            Vector2::new(90.0, -48.0),
            3.0,
            24,
            (-108.0, -66.0, 108.0, 66.0),
            false,
            true,
        ),
    ]);
}

#[test]
fn imported_dem_terminal_and_bend_keep_footprint_sources_through_cdt() {
    let terrain = kuopio_imported_dem_terrain();
    let (graph, surface, _, terminal_node) = compile_standard_span_with_nodes_on_terrain(
        &terrain,
        Vector2::new(-110.0, 80.0),
        Vector2::new(-18.0, 18.0),
        2.0,
        18,
    );
    assert_production_dem_case(ProductionDemCase {
        name: "raised terminal near imported Kuopio ridge-valley terrain",
        terrain,
        graph,
        surface,
        bounds: (-48.0, -12.0, 14.0, 48.0),
        sample_step_m: 2.0,
        expect_retaining_wall: false,
        expect_widened_tie_in: true,
        expected_node_piece: Some((terminal_node, RoadSurfaceVisualNodePieceKind::Terminal)),
    });

    let terrain = kuopio_imported_dem_terrain();
    let center = Vector2::new(0.0, 0.0);
    let (graph, center_node) =
        standard_node_graph_with_offset_roads(&terrain, center, 2.5, &[(-60.0, 0.0), (0.0, 60.0)]);
    let mut surface = RoadSurfaceSystem::new(16.0);
    surface.compile_dirty(&graph, &terrain);
    assert_production_dem_case(ProductionDemCase {
        name: "raised bend near imported Kuopio ridge-valley terrain",
        terrain,
        graph,
        surface,
        bounds: (-78.0, -18.0, 18.0, 78.0),
        sample_step_m: 2.0,
        expect_retaining_wall: false,
        expect_widened_tie_in: true,
        expected_node_piece: Some((center_node, RoadSurfaceVisualNodePieceKind::Bend)),
    });
}

#[test]
fn imported_dem_junction_keeps_node_footprint_sources_and_edit_order_stability() {
    let first = imported_four_way_junction_case(
        "raised four-way junction over imported Kuopio ridge-valley terrain",
        &[(-82.0, 58.0), (78.0, -48.0), (-42.0, -82.0), (54.0, 82.0)],
    );
    let reordered = imported_four_way_junction_case(
        "raised four-way junction over imported Kuopio ridge-valley terrain with reordered edits",
        &[(54.0, 82.0), (-42.0, -82.0), (78.0, -48.0), (-82.0, 58.0)],
    );

    let first_mesh = assert_production_dem_case(first);
    let reordered_mesh = assert_production_dem_case(reordered);
    assert_eq!(
        first_mesh.stats, reordered_mesh.stats,
        "reordered imported-road edits changed terrain-CDT diagnostics"
    );
    assert_eq!(
        canonical_emitted_face_set(&first_mesh),
        canonical_emitted_face_set(&reordered_mesh),
        "reordered imported-road edits changed emitted terrain topology"
    );
}

fn imported_four_way_junction_case(
    name: &'static str,
    endpoint_offsets: &[(f32, f32)],
) -> ProductionDemCase {
    standard_node_dem_case(
        name,
        kuopio_imported_dem_terrain(),
        Vector2::new(4.0, -8.0),
        3.0,
        endpoint_offsets,
        (-108.0, -108.0, 116.0, 108.0),
        false,
        true,
        RoadSurfaceVisualNodePieceKind::JunctionN,
    )
}

fn kuopio_imported_dem_terrain() -> TerrainSystem {
    let mut terrain = TerrainSystem::with_chunking(
        KUOPIO_IMPORTED_DEM_WIDTH,
        KUOPIO_IMPORTED_DEM_HEIGHT,
        KUOPIO_IMPORTED_DEM_CELL_M,
        8,
        0.0,
    );
    for (z, row) in KUOPIO_IMPORTED_DEM_HEIGHTS_DM.iter().enumerate() {
        for (x, height_dm) in row.iter().enumerate() {
            terrain.set_height(
                x,
                z,
                (f32::from(*height_dm) * 0.1) / crate::config::HEIGHT_SCALE,
            );
        }
    }
    terrain
}

