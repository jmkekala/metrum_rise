//! Exact incremental maintenance of prepared site rows owned by live buildings or parcels.
//!
//! Rows sort by owner, then key. Building owners are building indices; parcel owners are
//! the live building count plus the parcel storage index. A building row depends only on
//! its building and that building's parcel; a parcel row only on its parcel. Registry,
//! zoning-overlay, parcel-layout and network changes rebuild every row.

use crate::simulation::buildings::allocator::BuildingAllocator;
use crate::simulation::network::TransitNetwork;
use crate::simulation::zoning::ZoningSystem;

// Key fields that rebuild every row when changed.
const FULL_FIELDS: usize = 5;
const BUILDINGS: usize = 5;
const OCCUPANCY: usize = 6;
const BASE: usize = 7;

/// Revision of all prepared site rows; stored by each table across live forks.
pub(super) fn site_rows_key(
    allocator: &BuildingAllocator,
    zoning: &ZoningSystem,
    network: &TransitNetwork,
) -> [u64; 8] {
    [
        zoning.overlay_revision(),
        zoning.parcel_layout_revision(),
        allocator.registry.revision(),
        u64::from(network.cch_graph.build_generation),
        network.lane_system.revision(),
        allocator.building_ref_revision(),
        zoning.overlay_occupancy_revision(),
        allocator.buildings.len() as u64,
    ]
}

/// Owner rows changed since a table's previous key.
#[derive(Default)]
pub(super) struct SiteRowChanges {
    buildings: Vec<usize>,
    parcels: Vec<usize>,
    old_base: usize,
}

impl SiteRowChanges {
    /// Collects changed building and parcel rows since `previous`. Returns false when the
    /// table must rebuild every row. O(log log entries + changes).
    pub(super) fn collect(
        &mut self,
        previous: Option<&[u64]>,
        current: &[u64; 8],
        allocator: &BuildingAllocator,
        zoning: &ZoningSystem,
    ) -> bool {
        let Some(previous) = previous.filter(|previous| previous.len() == current.len()) else {
            return false;
        };
        if previous[..FULL_FIELDS] != current[..FULL_FIELDS] {
            return false;
        }
        self.old_base = previous[BASE] as usize;
        if !allocator.building_changes_since(previous[BUILDINGS], &mut self.buildings)
            || !zoning.occupancy_changes_since(previous[OCCUPANCY], &mut self.parcels)
        {
            return false;
        }
        // Every appended building must name its own row; otherwise the log is incomplete.
        let new_base = current[BASE] as usize;
        (self.old_base..new_base).all(|owner| self.buildings.binary_search(&owner).is_ok())
    }

    /// Changed rows regenerated by the last [`Self::merge`].
    pub(super) fn changed_owners(&self) -> usize {
        self.buildings.len() + self.parcels.len()
    }

    /// Moves unchanged rows, renumbers parcel owners and inserts regenerated owners in
    /// exact owner/key order. `regenerate(owner, previous)` receives the owner's previous
    /// rows under their old numbering. O(rows + changed owners) plus regeneration; unchanged
    /// rows are moved, never regenerated or cloned, and unrowed owners are never visited.
    #[allow(clippy::too_many_arguments)]
    pub(super) fn merge<T>(
        &self,
        previous: Vec<T>,
        new_base: usize,
        parcel_count: usize,
        owner: impl Fn(&T) -> usize,
        set_owner: impl Fn(&mut T, usize),
        key: impl Fn(&T) -> &str,
        mut regenerate: impl FnMut(usize, &[T]) -> Vec<T>,
    ) -> Vec<T> {
        let old_base = self.old_base;
        let mut rows = Vec::with_capacity(previous.len());
        let mut previous = previous.into_iter().peekable();
        let mut held = Vec::new();
        let emit = |rows: &mut Vec<T>, mut fresh: Vec<T>| {
            fresh.sort_unstable_by(|a, b| key(a).cmp(key(b)));
            rows.append(&mut fresh);
        };
        // Building block: rows of removed tail buildings disappear; changed owners regenerate.
        let keep_buildings = |rows: &mut Vec<T>,
                              previous: &mut std::iter::Peekable<std::vec::IntoIter<T>>,
                              before: usize| {
            while let Some(row) = previous.next_if(|row| owner(row) < before.min(old_base)) {
                if owner(&row) < new_base {
                    rows.push(row);
                }
            }
        };
        for &building in &self.buildings {
            keep_buildings(&mut rows, &mut previous, building);
            held.clear();
            while let Some(row) =
                previous.next_if(|row| owner(row) == building && building < old_base)
            {
                held.push(row);
            }
            if building < new_base {
                emit(&mut rows, regenerate(building, &held));
            }
        }
        keep_buildings(&mut rows, &mut previous, usize::MAX);
        // Parcel block: storage is unchanged, so retained rows only shift with the base.
        let keep_parcels = |rows: &mut Vec<T>,
                            previous: &mut std::iter::Peekable<std::vec::IntoIter<T>>,
                            before: usize| {
            while let Some(mut row) = previous.next_if(|row| owner(row) < old_base + before) {
                let parcel = owner(&row) - old_base;
                set_owner(&mut row, new_base + parcel);
                rows.push(row);
            }
        };
        for &parcel in &self.parcels {
            if parcel >= parcel_count {
                break;
            }
            keep_parcels(&mut rows, &mut previous, parcel);
            held.clear();
            while let Some(row) = previous.next_if(|row| owner(row) == old_base + parcel) {
                held.push(row);
            }
            emit(&mut rows, regenerate(new_base + parcel, &held));
        }
        keep_parcels(&mut rows, &mut previous, parcel_count);
        debug_assert!(
            previous.next().is_none(),
            "parcel rows must stay within parcel storage"
        );
        rows
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[derive(Clone, Debug, PartialEq)]
    struct Row {
        owner: usize,
        key: String,
        tag: u32,
    }

    fn row(owner: usize, key: &str, tag: u32) -> Row {
        Row {
            owner,
            key: key.into(),
            tag,
        }
    }

    fn merge(
        changes: &SiteRowChanges,
        previous: Vec<Row>,
        new_base: usize,
        parcels: usize,
        fresh: &dyn Fn(usize) -> Vec<Row>,
    ) -> Vec<Row> {
        changes.merge(
            previous,
            new_base,
            parcels,
            |r| r.owner,
            |r, o| r.owner = o,
            |r| r.key.as_str(),
            |owner, _| fresh(owner),
        )
    }

    #[test]
    fn merge_matches_a_full_sorted_rebuild_after_append_removal_and_occupancy_changes() {
        // Three buildings and four parcels; parcel owners start at base 3.
        let previous = vec![
            row(0, "a", 0),
            row(1, "b", 1),
            row(1, "c", 2),
            row(2, "d", 3),
            row(3, "p0", 4),
            row(5, "p2", 5),
            row(6, "x", 6),
            row(6, "y", 7),
        ];
        // Building 1 is removed by swap (2 moves to 1), then one building is appended at 2;
        // parcel 1 becomes available and parcel 3 is occupied.
        let changes = SiteRowChanges {
            buildings: vec![1, 2],
            parcels: vec![1, 3],
            old_base: 3,
        };
        let fresh = |owner: usize| match owner {
            1 => vec![row(1, "z", 10), row(1, "d", 11)],
            2 => vec![row(2, "n", 12)],
            4 => vec![row(4, "p1", 13)],
            _ => Vec::new(),
        };
        let rows = merge(&changes, previous, 3, 4, &fresh);
        assert_eq!(
            rows,
            vec![
                row(0, "a", 0),
                row(1, "d", 11),
                row(1, "z", 10),
                row(2, "n", 12),
                row(3, "p0", 4),
                row(4, "p1", 13),
                row(5, "p2", 5)
            ]
        );
    }

    #[test]
    fn merge_shifts_parcel_owners_and_drops_a_removed_tail_building() {
        let previous = vec![
            row(0, "a", 0),
            row(1, "b", 1),
            row(2, "p0", 2),
            row(3, "p1", 3),
        ];
        let changes = SiteRowChanges {
            buildings: vec![1],
            parcels: vec![],
            old_base: 2,
        };
        let rows = merge(&changes, previous, 1, 2, &|_| Vec::new());
        assert_eq!(rows, vec![row(0, "a", 0), row(1, "p0", 2), row(2, "p1", 3)]);
    }
}
